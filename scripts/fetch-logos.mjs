// Usage: npm run fetch-logos
// Downloads the highest-resolution official icon each brand publishes (apple-touch-icon / PNG
// icon links on its own website) into assets/logos, then regenerates src/logos.ts.
// To use official press-kit artwork instead, drop PNG files into assets/logos named exactly
// like the slug below (e.g. mcdonalds.png). Existing files are never overwritten.
import fs from 'node:fs';
import path from 'node:path';

const BRANDS = {
  "McDonald's": ['mcdonalds', 'https://www.mcdonalds.com'],
  KFC: ['kfc', 'https://www.kfc.com'],
  'Burger King': ['burgerking', 'https://www.bk.com'],
  'Pizza Hut': ['pizzahut', 'https://www.pizzahut.com'],
  Starbucks: ['starbucks', 'https://www.starbucks.com'],
  'Costa Coffee': ['costacoffee', 'https://www.costacoffee.com'],
  'Tim Hortons': ['timhortons', 'https://www.timhortons.com'],
  "Dunkin'": ['dunkin', 'https://www.dunkindonuts.com'],
  'Papa Johns': ['papajohns', 'https://www.papajohns.com'],
  Subway: ['subway', 'https://www.subway.com'],
  'Zaatar w Zeit': ['zaatarwzeit', 'https://www.zaatarwzeit.com'],
  Jollibee: ['jollibee', 'https://www.jollibeefoods.com'],
  Talabat: ['talabat', 'https://www.talabat.com'],
  Smiles: ['smiles', 'https://smiles.ae'],
  Keeta: ['keeta', 'https://www.keeta-global.com'],
  Noon: ['noon', 'https://www.noon.com'],
  'Amazon.ae': ['amazon', 'https://www.amazon.ae'],
  Namshi: ['namshi', 'https://www.namshi.com'],
  'Brands For Less': ['brandsforless', 'https://www.brandsforless.com'],
  Centrepoint: ['centrepoint', 'https://www.centrepointstores.com'],
  Carrefour: ['carrefour', 'https://www.carrefouruae.com'],
  'Lulu Hypermarket': ['lulu', 'https://www.luluhypermarket.com'],
};

const OUT = path.resolve('assets/logos');
fs.mkdirSync(OUT, { recursive: true });
const UA = { 'user-agent': 'Mozilla/5.0 (compatible; WafferLogoFetcher/1.0)' };

const pngSize = (b) => (b.length > 24 && b.readUInt32BE(0) === 0x89504e47 ? b.readUInt32BE(16) : 0);

async function candidates(site) {
  const list = [`${site}/apple-touch-icon.png`, `${site}/apple-touch-icon-precomposed.png`];
  try {
    const html = await (await fetch(site, { headers: UA, redirect: 'follow' })).text();
    for (const m of html.matchAll(/<link[^>]+rel=["'][^"']*(?:apple-touch-icon|icon)[^"']*["'][^>]*>/gi)) {
      const href = /href=["']([^"']+)["']/i.exec(m[0])?.[1];
      if (href && !/\.(svg|ico)(\?|$)/i.test(href)) list.push(new URL(href, site).href);
    }
  } catch {}
  return list;
}

const found = {};
for (const [name, [slug, site]] of Object.entries(BRANDS)) {
  const file = path.join(OUT, `${slug}.png`);
  if (fs.existsSync(file)) { found[name] = slug; console.log(`✓ ${name} (already present)`); continue; }
  let best = null;
  for (const url of await candidates(site)) {
    try {
      const r = await fetch(url, { headers: UA });
      if (!r.ok) continue;
      const buf = Buffer.from(await r.arrayBuffer());
      const w = pngSize(buf);
      if (w >= 120 && (!best || w > best.w)) best = { w, buf, url };
    } catch {}
  }
  if (best) { fs.writeFileSync(file, best.buf); found[name] = slug; console.log(`✓ ${name} ${best.w}px ← ${best.url}`); }
  else console.log(`✗ ${name}: nothing ≥120px found. Drop a PNG at assets/logos/${slug}.png`);
}

const lines = Object.entries(found).map(([n, s]) => `  ${JSON.stringify(n)}: require('../assets/logos/${s}.png'),`);
fs.writeFileSync('src/logos.ts', `// AUTO-GENERATED by \`npm run fetch-logos\`. Do not edit by hand.\nexport const LOCAL_LOGOS: Record<string, any> = {\n${lines.join('\n')}\n};\n`);
console.log(`\nWrote src/logos.ts with ${lines.length} logos. Restart Expo with: npx expo start -c`);
